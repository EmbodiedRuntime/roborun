"""Write the stack figure: what you build on roborun, its core, and the robots below (like Ray's).

    python docs/media/stack_svg.py docs/media/stack.svg
"""
import sys
from pathlib import Path

W, PAD, LABEL = 900, 14, 196
X0 = LABEL + PAD  # chips start here
ROWS = [
    ("Policies", "may be slow or wrong", "drive",
     [("Programs", "a tool call or full code, written or generated"), ("End-to-end models", "VLA · WAM")]),
    ("roborun", "", "core",
     [("Task", "owned, stoppable activity"), ("World", "shared, time-stamped state"),
      ("Gate", "checks every command"), ("Trace", "what ran, on which data")]),
    ("Robots", "continuous, irreversible", "robot",
     [("Simulation", ""), ("Real world", "")]),
]
o: list[str] = []
a = o.append
y = 8
heights = {"core": 64}
body = []
for title, note, kind, chips in ROWS:
    h = heights.get(kind, 50)
    body.append((title, note, kind, chips, y, h))
    y += h + 2 * PAD + 6
H = y

a(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
  'aria-label="Policies are programs (from a single tool call to full code, written by people or '
  'generated by models) or end-to-end models (VLA, world action models); they may be slow or wrong. Robots, '
  'in simulation or the real world, are continuous and irreversible. roborun sits between them: Task makes '
  'every running activity owned by whoever started it and stoppable, World holds shared, time-stamped state, Gate checks every command, and Trace '
  'records what ran, on which data.">')
a("""<style>
text{font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif;fill:#1f2328}
.band{fill:#f6f8fa;stroke:#d1d9e0}.bandcore{fill:#e8edff;stroke:#2848d8;stroke-width:1.5}
.chip{fill:#ffffff;stroke:#d1d9e0}.chipcore{fill:#ffffff;stroke:#2848d8;stroke-width:1.5}
.planned{fill:none;stroke:#8c959f;stroke-dasharray:4 3}
.lab{font-size:13px;font-weight:700;fill:#59636e}.labcore{font-size:17px;font-weight:800;fill:#2848d8}
.c{font-size:14px;font-weight:600}.note{font-size:12px;font-style:italic;fill:#59636e}.cc{font-size:15px;font-weight:700}.cs{font-size:12px;fill:#59636e}
.dim{fill:#8c959f}
@media (prefers-color-scheme: dark){text{fill:#e6edf3}.band{fill:#151b23;stroke:#3d444d}
.bandcore{fill:#18224f;stroke:#7b8fff}.chip{fill:#0d1117;stroke:#3d444d}.chipcore{fill:#0d1117;stroke:#7b8fff}
.planned{stroke:#6e7681}.lab,.cs,.note{fill:#9198a1}.labcore{fill:#7b8fff}.dim{fill:#6e7681}}
</style>""")
for title, note, kind, chips, y, h in body:
    core = kind == "core"
    a(f'<rect class="{"bandcore" if core else "band"}" x="2" y="{y}" width="{W - 4}" height="{h + 2 * PAD}" rx="12"/>')
    ty = y + PAD + h / 2 + (5 if not note else -4)
    a(f'<text class="{"labcore" if core else "lab"}" x="{PAD + 6}" y="{ty}">{title}</text>')
    if note:
        a(f'<text class="note" x="{PAD + 6}" y="{ty + 18}">{note}</text>')
    n = len(chips)
    gap = 10
    cw = (W - X0 - PAD - gap * (n - 1)) / n
    for i, (name, sub) in enumerate(chips):
        x = X0 + i * (cw + gap)
        planned = sub == "planned"
        cls = "planned" if planned else ("chipcore" if core else "chip")
        a(f'<rect class="{cls}" x="{x}" y="{y + PAD}" width="{cw}" height="{h}" rx="8"/>')
        if core:
            a(f'<text class="cc" x="{x + cw / 2}" y="{y + PAD + 27}" text-anchor="middle">{name}</text>')
            a(f'<text class="cs" x="{x + cw / 2}" y="{y + PAD + 47}" text-anchor="middle">{sub}</text>')
        elif sub:
            a(f'<text class="c" x="{x + cw / 2}" y="{y + PAD + 21}" text-anchor="middle">{name}</text>')
            a(f'<text class="cs" x="{x + cw / 2}" y="{y + PAD + 39}" text-anchor="middle">{sub}</text>')
        else:
            a(f'<text class="c" x="{x + cw / 2}" y="{y + PAD + h / 2 + 5}" text-anchor="middle">{name}</text>')
a("</svg>")
Path(sys.argv[1]).write_text("\n".join(o) + "\n")
